// שדות מחיר החבילה / מחיר לתמונה נוספת (components/PriceInput.tsx) עולים ויורדים
// בקפיצות של 10 ₪ (חיצים במקלדת, חיצי השדה, גלגלת). step=10 רגיל היה הופך כל
// סכום שאינו כפולה של 10 (למשל 355) ל"לא תקין" וחוסם את שליחת הטופס - לכן
// בסיס הצעד (min) הוא ספרת האחדות של הערך הנוכחי: 355 -> min=5, וכך 355 תקין
// והחיצים מביאים ל-345 / 365. הבסיס תמיד קטן או שווה לערך, אז שום סכום
// חיובי שהוקלד לא נחסם, וערך שלילי עדיין נחסם (הבסיס אז 0).

export const PRICE_STEP = 10;

// בסיס הצעד כמחרוזת (הספרות אחרי הנקודה נשמרות כמו שהוקלדו, כדי שהדפדפן
// יחשב את התקינות בלי שגיאות עיגול של נקודה צפה).
export function priceStepBase(value: string): string {
  // ".5" (בלי ספרה לפני הנקודה) הוא ערך תקין בשדה מספר - מנרמלים ל-"0.5"
  const normalised = value.replace(/^\s*\./, '0.');
  const match = /^\s*\d*(\d)(\.\d*)?\s*$/.exec(normalised);
  if (!match) return '0';
  const frac = match[2] && match[2].length > 1 ? match[2] : '';
  return `${match[1]}${frac}`;
}
